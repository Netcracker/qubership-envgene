from envgenehelper import INVENTORY_DIR_NAME, Path, beautifyYaml, getEnvDefinitionPath, get_namespaces, \
    get_schema_dir, logger, openFileAsString, readYaml, set_nested_yaml_attribute, writeYamlToFile
from envgenehelper.deploy_plan_adapter import DELTA_DEPLOY_PLAN_FILE_NAME, DEPLOY_PLAN_FILE_NAME, DeployPlanEntity, \
    EnvgeneDeployPlan

DEPLOYMENT_PROFILE_NAME = "deployment-profile"
RESOURCE_PROFILES_DIR_NAME = "resource_profiles"
RESOURCE_PROFILE_SCHEMA = "resource-profile.schema.json"
GENERATED_MARKER = "Generated by EnvGene from the PROFILE pipeline parameter."
GENERATED_HEADER = f"{GENERATED_MARKER}\nDo not edit: the next run with PROFILE rewrites this file."


def application_name(entity: DeployPlanEntity) -> str:
    return entity.version.split(":")[0]


def deployed_entities(env_dir: Path) -> list[DeployPlanEntity] | None:
    inventory = env_dir / INVENTORY_DIR_NAME
    delta_plan = inventory / DELTA_DEPLOY_PLAN_FILE_NAME
    plan = inventory / DEPLOY_PLAN_FILE_NAME
    plan_path = delta_plan if delta_plan.is_file() else plan
    if not plan_path.is_file():
        logger.warning(f"Neither '{delta_plan}' nor '{plan}' is found, so the applications deployed by this run are "
                       f"unknown and the '{DEPLOYMENT_PROFILE_NAME}' override is not generated")
        return None
    entities = [entity for entity in EnvgeneDeployPlan.read(plan_path).entities if application_name(entity)]
    if not entities and plan_path != plan and plan.is_file():
        logger.info(f"'{plan_path}' deploys no application, the applications are read from '{plan}'")
        plan_path = plan
        entities = [entity for entity in EnvgeneDeployPlan.read(plan).entities if application_name(entity)]
    if not entities:
        logger.warning(f"'{plan_path}' deploys no application, so the '{DEPLOYMENT_PROFILE_NAME}' override is not "
                       f"generated")
        return None
    logger.info(f"Applications deployed by this run, read from '{plan_path}': "
                f"{', '.join(dict.fromkeys(application_name(entity) for entity in entities))}")
    return entities


def build_deployment_profile_override(entities: list[DeployPlanEntity], profile_name: str) -> dict:
    applications = dict.fromkeys(application_name(entity) for entity in entities)
    overridden = [{"name": application, "baseline": profile_name, "services": []} for application in applications]
    logger.info(f"The '{DEPLOYMENT_PROFILE_NAME}' override sets baseline '{profile_name}' as the default of "
                f"{len(overridden)} deployed application(s)")
    return {"name": DEPLOYMENT_PROFILE_NAME, "applications": overridden}


def write_deployment_profile_override(env_dir: Path, entities: list[DeployPlanEntity], profile_name: str) -> Path:
    override = build_deployment_profile_override(entities, profile_name)
    override_path = env_dir / INVENTORY_DIR_NAME / RESOURCE_PROFILES_DIR_NAME / f"{DEPLOYMENT_PROFILE_NAME}.yml"
    if override_path.is_file() and not openFileAsString(override_path).startswith(f"# {GENERATED_MARKER}"):
        logger.warning(f"'{override_path}' was not generated by EnvGene and is overwritten by the override generated "
                       f"from PROFILE. The name '{DEPLOYMENT_PROFILE_NAME}' is reserved for this step")
    override_path.parent.mkdir(parents=True, exist_ok=True)
    logger.info(f"Writing the '{DEPLOYMENT_PROFILE_NAME}' override with baseline '{profile_name}' to '{override_path}'")
    writeYamlToFile(override_path, override, schema_name=RESOURCE_PROFILE_SCHEMA, schemas_dir=get_schema_dir())
    beautifyYaml(override_path, header_text=GENERATED_HEADER)
    return override_path


def deployed_override_keys(env_dir: Path, entities: list[DeployPlanEntity]) -> list[str]:
    folder_by_namespace = {namespace.name: namespace.path.name for namespace in get_namespaces(env_dir)}
    keys = {folder_by_namespace.get(entity.namespace, entity.deploy_postfix) for entity in entities}
    return sorted(key for key in keys if key)


def append_override_to_env_definition(env_dir: Path, keys: list[str],
                                      override_name: str = DEPLOYMENT_PROFILE_NAME) -> list[str]:
    env_definition_path = Path(getEnvDefinitionPath(str(env_dir)))
    env_definition = readYaml(env_definition_path)
    profiles = env_definition.get("envTemplate", {}).get("envSpecificResourceProfiles") or {}
    appended = []
    for key in keys:
        current = profiles.get(key)
        names = [current] if isinstance(current, str) else list(current or [])
        if override_name in names:
            continue
        names.append(override_name)
        set_nested_yaml_attribute(env_definition, f"envTemplate.envSpecificResourceProfiles.{key}", names)
        appended.append(key)
    if not appended:
        logger.info(f"The override list of every deployed namespace already holds '{override_name}'")
        return appended
    logger.info(f"'{override_name}' is appended last to the override list of: {', '.join(appended)}")
    writeYamlToFile(env_definition_path, env_definition)
    return appended


def apply_deployment_profile(env_dir: Path, profile_name: str) -> Path | None:
    entities = deployed_entities(env_dir)
    if entities is None:
        return None
    override_path = write_deployment_profile_override(env_dir, entities, profile_name)
    append_override_to_env_definition(env_dir, deployed_override_keys(env_dir, entities))
    return override_path
