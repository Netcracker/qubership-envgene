from envgenehelper import INVENTORY_DIR_NAME, NamespaceRole, Path, beautifyYaml, getEnvDefinitionPath, \
    get_bgd_object, get_namespaces, get_namespace_role, get_schema_dir, getenv, logger, openFileAsString, \
    parse_bg_ns_target, readYaml, set_nested_yaml_attribute, writeYamlToFile
from envgenehelper.deploy_plan_adapter import DELTA_DEPLOY_PLAN_FILE_NAME, DEPLOY_PLAN_FILE_NAME, DeployPlanEntity, \
    EnvgeneDeployPlan

PROFILE_OVERRIDE_SUFFIX = "-profile-override"
GENERATED_PROFILES_MAP_KEY = "generatedProfileDefaults"
RESOURCE_PROFILES_DIR_NAME = "resource_profiles"
RESOURCE_PROFILE_SCHEMA = "resource-profile.schema.json"
GENERATED_MARKER = "Generated by EnvGene from the PROFILE pipeline parameter."
PROFILE_DOC_URL = "https://github.com/Netcracker/qubership-envgene/blob/main/docs"
PROFILE_DOC = f"{PROFILE_DOC_URL}/features/resource-profile.md#override-generated-by-a-pipeline-run"
GENERATED_HEADER = (f"{GENERATED_MARKER}\nDo not edit: the next run with PROFILE updates the baseline of the "
                    f"applications it deploys and keeps the other applications.\nIt is applied on top of the resource "
                    f"profile of the Namespace.\n{PROFILE_DOC}")
GENERATED_KEY_COMMENT = "Generated by EnvGene from the PROFILE pipeline parameter, do not edit."
BG_ROLE_SUFFIXES = {NamespaceRole.ORIGIN: "-origin", NamespaceRole.PEER: "-peer"}


def profile_override_name(deploy_postfix: str) -> str:
    return f"{deploy_postfix}{PROFILE_OVERRIDE_SUFFIX}"


def application_name(entity: DeployPlanEntity) -> str:
    return entity.version.split(":")[0]


def deployed_entities(env_dir: Path) -> list[DeployPlanEntity] | None:
    inventory = env_dir / INVENTORY_DIR_NAME
    delta_plan = inventory / DELTA_DEPLOY_PLAN_FILE_NAME
    plan = inventory / DEPLOY_PLAN_FILE_NAME
    plan_path = delta_plan if delta_plan.is_file() else plan
    if not plan_path.is_file():
        logger.warning(f"Neither '{delta_plan}' nor '{plan}' is found, so the applications deployed by this run are "
                       f"unknown and no '{PROFILE_OVERRIDE_SUFFIX}' override is generated")
        return None
    entities = [entity for entity in EnvgeneDeployPlan.read(plan_path).entities if application_name(entity)]
    if not entities and plan_path != plan and plan.is_file():
        logger.info(f"'{plan_path}' deploys no application, the applications are read from '{plan}'")
        plan_path = plan
        entities = [entity for entity in EnvgeneDeployPlan.read(plan).entities if application_name(entity)]
    if not entities:
        logger.warning(f"'{plan_path}' deploys no application, so no '{PROFILE_OVERRIDE_SUFFIX}' override is "
                       f"generated")
        return None
    logger.info(f"Applications deployed by this run, read from '{plan_path}': "
                f"{', '.join(dict.fromkeys(application_name(entity) for entity in entities))}")
    return entities


def deployed_groups(env_dir: Path, entities: list[DeployPlanEntity]) -> dict[str, list[str]]:
    folder_by_namespace = {namespace.name: namespace.postfix for namespace in get_namespaces(env_dir)}
    bgd = get_bgd_object(env_dir) or {}
    bg_ns_target = parse_bg_ns_target(getenv("BG_NS_TARGET"))
    keys_by_postfix: dict[str, list[str]] = {}
    for entity in entities:
        postfix = entity.deploy_postfix
        if not postfix:
            logger.warning(f"Entry '{entity.version}' of the deployment plan has no deployPostfix, its baseline is "
                           f"not written into any '{PROFILE_OVERRIDE_SUFFIX}' override")
            continue
        key = namespace_key(entity, folder_by_namespace, bgd, bg_ns_target)
        if key is None:
            continue
        keys = keys_by_postfix.setdefault(postfix, [])
        if key not in keys:
            keys.append(key)
    return {postfix: sorted(keys) for postfix, keys in sorted(keys_by_postfix.items())}


def namespace_key(entity: DeployPlanEntity, folder_by_namespace: dict[str, str], bgd: dict,
                  bg_ns_target: NamespaceRole | None) -> str | None:
    folder = folder_by_namespace.get(entity.namespace)
    if folder:
        return folder
    if bgd.get("originNamespace") or bgd.get("peerNamespace"):
        return f"{entity.deploy_postfix}{BG_ROLE_SUFFIXES.get(get_namespace_role(entity.namespace, bgd), '')}"
    if bg_ns_target:
        logger.warning(f"The Namespace '{entity.namespace}' of deployPostfix '{entity.deploy_postfix}' has no folder "
                       f"and the environment has no 'bg_domain.yml', so neither its origin nor its peer side is known "
                       f"and no '{GENERATED_PROFILES_MAP_KEY}' key is recorded for it, although its override file is "
                       f"written")
        return None
    return entity.deploy_postfix


def build_profile_override(deploy_postfix: str, entities: list[DeployPlanEntity], profile_name: str) -> dict:
    applications = dict.fromkeys(application_name(entity) for entity in entities)
    overridden = [{"name": application, "baseline": profile_name, "services": []} for application in applications]
    logger.info(f"'{profile_override_name(deploy_postfix)}' sets baseline '{profile_name}' as the baseline of "
                f"{len(overridden)} deployed application(s)")
    return {"name": profile_override_name(deploy_postfix), "applications": overridden}


def merge_applications(existing_applications: list | None, generated_applications: list[dict]) -> list[dict]:
    current = {application["name"]: application for application in generated_applications}
    merged = []
    merged_names = set()
    for application in existing_applications or []:
        name = application.get("name") if isinstance(application, dict) else None
        if not name or name in merged_names:
            continue
        merged_names.add(name)
        merged.append(current.pop(name, application))
    merged.extend(application for application in generated_applications if application["name"] not in merged_names)
    return merged


def write_profile_override(env_dir: Path, deploy_postfix: str, entities: list[DeployPlanEntity],
                           profile_name: str) -> Path:
    override = build_profile_override(deploy_postfix, entities, profile_name)
    file_name = f"{profile_override_name(deploy_postfix)}.yml"
    override_path = env_dir / INVENTORY_DIR_NAME / RESOURCE_PROFILES_DIR_NAME / file_name
    if override_path.is_file():
        if openFileAsString(override_path).startswith(f"# {GENERATED_MARKER}"):
            existing = readYaml(override_path) or {}
            deployed_names = {application["name"] for application in override["applications"]}
            override["applications"] = merge_applications(existing.get("applications"), override["applications"])
            kept = [application["name"] for application in override["applications"]
                    if application["name"] not in deployed_names]
            if kept:
                logger.info(f"'{override_path}' keeps the baseline of the {len(kept)} application(s) this run does "
                            f"not deploy: {', '.join(kept)}")
        else:
            logger.warning(f"'{override_path}' was not generated by EnvGene and is overwritten by the override "
                           f"generated from PROFILE. The name '{profile_override_name(deploy_postfix)}' is reserved "
                           f"for this step")
    override_path.parent.mkdir(parents=True, exist_ok=True)
    logger.info(f"Writing the override of '{deploy_postfix}' with baseline '{profile_name}' to '{override_path}'")
    writeYamlToFile(override_path, override, schema_name=RESOURCE_PROFILE_SCHEMA, schemas_dir=get_schema_dir())
    beautifyYaml(override_path, header_text=GENERATED_HEADER)
    return override_path


def assign_generated_overrides(env_dir: Path, overrides_by_key: dict[str, str]) -> list[str]:
    env_definition_path = Path(getEnvDefinitionPath(str(env_dir)))
    env_definition = readYaml(env_definition_path)
    generated = env_definition.get("envTemplate", {}).get(GENERATED_PROFILES_MAP_KEY) or {}
    assigned = []
    for key, override_name in overrides_by_key.items():
        if generated.get(key) == override_name:
            continue
        set_nested_yaml_attribute(env_definition, f"envTemplate.{GENERATED_PROFILES_MAP_KEY}.{key}", override_name,
                                  comment=GENERATED_KEY_COMMENT)
        assigned.append(key)
    if not assigned:
        logger.info(f"Every deployed Namespace already references its '{PROFILE_OVERRIDE_SUFFIX}' override in "
                    f"'{GENERATED_PROFILES_MAP_KEY}'")
        return assigned
    logger.info(f"'{GENERATED_PROFILES_MAP_KEY}' is set for: "
                f"{', '.join(f'{key} = {overrides_by_key[key]}' for key in assigned)}")
    writeYamlToFile(env_definition_path, env_definition)
    return assigned


def apply_deployment_profile(env_dir: Path, profile_name: str) -> list[Path]:
    entities = deployed_entities(env_dir)
    if entities is None:
        return []
    overrides_by_key = {}
    override_paths = []
    for postfix, keys in deployed_groups(env_dir, entities).items():
        postfix_entities = [entity for entity in entities if entity.deploy_postfix == postfix]
        override_paths.append(write_profile_override(env_dir, postfix, postfix_entities, profile_name))
        for key in keys:
            overrides_by_key[key] = profile_override_name(postfix)
    assign_generated_overrides(env_dir, overrides_by_key)
    return override_paths
